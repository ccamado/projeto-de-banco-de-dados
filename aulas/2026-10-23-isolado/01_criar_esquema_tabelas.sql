-- Se já executou este roteiro, o script pode ser rodado novamente sem apagar dados.
CREATE SCHEMA IF NOT EXISTS cepef_pratica;

CREATE TABLE IF NOT EXISTS cepef_pratica.categorias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(60) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS cepef_pratica.turmas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(20) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS cepef_pratica.avisos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo VARCHAR(120) NOT NULL CHECK (length(trim(titulo)) >= 3),
 descricao TEXT NOT NULL,
 categoria_id BIGINT NOT NULL REFERENCES cepef_pratica.categorias(id),
 turma_id BIGINT NOT NULL REFERENCES cepef_pratica.turmas(id),
 publicado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX IF NOT EXISTS idx_avisos_categoria ON cepef_pratica.avisos(categoria_id);
CREATE INDEX IF NOT EXISTS idx_avisos_turma ON cepef_pratica.avisos(turma_id);
-- Isolamento: tudo fica dentro de cepef_pratica, sem modificar tabelas public existentes.
-- Segurança: não conceder acesso público automaticamente ao esquema.
